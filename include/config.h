#pragma once
#include <Arduino.h>
#include <Preferences.h>

// =====================================================================
//  POV Wheel Display — аппаратная ревизия V5
//  6 лучей × 88 диодов SK9822-A (по 44 на каждой стороне луча),
//  6 датчиков Холла DRV5023 (по одному на луч), два DCDC TPS631000,
//  зарядник IP2312U, датчик света ALS-PT19, вибродатчик HX 0805-C2.
// =====================================================================

// --- ПАРАМЕТРЫ ДИСПЛЕЯ ---
#define NUM_ARMS        6                              // Лучей всегда 6 (задано железом)
#define LEDS_PER_SIDE   44                             // Диодов на одной стороне луча
#define LEDS_PER_ARM    (LEDS_PER_SIDE * 2)            // 88 диодов на луче (обе стороны)
#define NUM_LEDS        (NUM_ARMS * LEDS_PER_ARM)      // 528 диодов в цепочке
#define SECTORS         360                            // Угловое разрешение кадра
#define ARM_STEP_DEG    (360 / NUM_ARMS)               // 60° между соседними лучами

// Пиксель кадра — RGB565 (little-endian): (r5<<11) | (g6<<5) | b5.
// 5 бит на R/B хватает с запасом ради того, для чего вообще нужна площадная
// выборка в браузере — субдиодного позиционирования края: шаг уровня 8/255
// куда мельче, чем видно на вращающемся ободе. Плавные градиенты на 32 уровнях
// полосили бы, поэтому конвертер сеет упорядоченный дизеринг (Байер 4×4).
// Распаковка на устройстве бесплатна: код 5/6 бит — это сразу индекс в
// lut_tone5/lut_tone6, то есть одна 16-битная загрузка вместо трёх байтовых.
#define FRAME_SIZE      (SECTORS * LEDS_PER_SIDE * 2)  // 31680 байт на кадр
#define FRAME_SIZE_888  (SECTORS * LEDS_PER_SIDE * 3)  // 47520 — старый формат, читается для совместимости

// Физическая геометрия луча — радиусы центров крайних диодов (мм).
// Лучи расходятся строго из центра оси, поэтому все диоды стороны лежат на
// одном радиусе-луче и угловой поправки на смещение не требуется.
#define LED_R_INNER_MM  49.0f
#define LED_R_OUTER_MM  273.0f

// Радиальная компенсация яркости, %: 0 = выключена, 100 = полная (яркость ∝ r).
// Зафиксирована — подобранное значение, регулировать из веба больше нечего.
#define RADIAL_GAIN_PCT 80.0f

// --- ПИНЫ ESP32-S3 (V5) ---
#define PIN_LED_DATA       11   // SK9822 DATA (SPI MOSI)
#define PIN_LED_CLK        12   // SK9822 CLK
#define PIN_BUTTON          0   // Кнопка (boot)
#define PIN_VIBRATION      15   // HX 0805-C2: импульсы LOW, источник пробуждения из сна
#define PIN_EN_DCDC_ARM1   10   // TPS631000 №1: луч 1 + Холл 1 + датчик света
#define PIN_EN_DCDC_REST   38   // TPS631000 №2: лучи 2–6 + Холлы 2–6
#define PIN_ADC_VUSB        6   // ADC1_CH5, делитель 12к/12к (1:2) от VUSB
#define PIN_ADC_VBAT        7   // ADC1_CH6, делитель 1:2 от VBAT
#define PIN_CHG_STAT        8   // IP2312U D2 через делитель: HIGH = заряд завершён
#define PIN_ADC_LIGHT       9   // ADC1_CH8, ALS-PT19 (нагрузка 12к), питание от DCDC №1

// Датчики Холла DRV5023 — по одному на каждый луч.
// Выходы open-drain подтянуты резисторами 1к к неотключаемой линии 3V3.
#define HALL_COUNT      NUM_ARMS
#define HALL_PIN_LIST   { 13, 21, 14, 18, 17, 16 }

// Пороги включения/выключения отрисовки, об/мин (гистерезис 20 RPM)
#define RPM_RENDER_ON   120.0f
#define RPM_RENDER_OFF  100.0f

// --- ПАРАМЕТРЫ УГЛОВОЙ ЧЁТКОСТИ ---
// Тактовая частота SPI для SK9822. Частота напрямую задаёт угловое разрешение:
// пока кадр уходит по шине, луч продолжает поворачиваться, и весь этот угол
// показывается одними и теми же данными.
//
// ВНИМАНИЕ: источник тактирования SPI в этой версии IDF жёстко привязан к APB
// 80 МГц, а делители целые (f = 80 / (pre·n), pre 1–16, n 2–64). Поэтому набор
// достижимых частот здесь дискретный: 40 / 26.67 / 20 / 16 / 13.3 МГц.
// Значений между 20 и 26.67 не существует — 25 МГц получить нельзя.
// Фактическая частота пишется в лог при старте.
#define SK9822_SPI_HZ   20000000

// Скважность тактового сигнала, 1/256 доли периода (128 = 50 %).
// Драйвер считает длительность высокого уровня как h = round(duty·n/256)
// тактов APB (12.5 нс каждый), где n — делитель. При НЕЧЁТНОМ n ровно 50 %
// недостижимо, и это ключевой момент для длинной цепочки:
//   20    МГц (n=4): h=2 → 50 %,  фазы 25.0 / 25.0 нс
//   26.67 МГц (n=3): h=1 → 33 %,  фазы 12.5 / 25.0 нс   ← duty 128
//                    h=2 → 67 %,  фазы 25.0 / 12.5 нс   ← duty 170
//   40    МГц (n=2): h=1 → 50 %,  фазы 12.5 / 12.5 нс
// Первый луч тактируется самим ESP32 через IO_MUX (IO11/IO12 — штатные пины
// SPI2) и переваривает короткую фазу; дальше по цепочке CKO гонит слабый выход
// SK9822 через разъём и 50 мм, фронты заваливаются, и 12.5 нс не хватает.
// Если на 26.67 МГц сыпятся лучи 2–6 — попробовать 170: короткой станет другая
// фаза, и станет видно, чего именно не хватает чипу.
#define SK9822_DUTY_POS 128

// Минимальный угловой шаг между обновлениями ленты, градусы.
// 0.5° на радиусе 273 мм — 2.4 мм, вдвое мельче шага диодов. Мельче смысла нет:
// упрёмся в пропускную способность SPI, а на малых оборотах только сожжём CPU.
#define ANGLE_MIN_STEP  0.5f

// Коэффициент подстройки фазы по событию Холла (ФАПЧ), 0…1.
// 1.0 — жёсткая привязка, как раньше: остаточная погрешность калибровки датчика
// сразу становится скачком картинки, и за оборот выходит шесть чуть смещённых
// копий изображения («веер» на периферии). Меньший K размазывает эту погрешность
// по обороту, оставляя среднюю фазу той же.
#define HALL_PLL_K      0.25f

// Коэффициент делителей VBAT/VUSB (два одинаковых резистора → ×2)
#define ADC_DIVIDER_RATIO   2.0f

// Освещённость, при которой яркость выходит на максимум.
// ALS-PT19 с нагрузкой 12к даёт ≈2400 мВ при 1000 лк.
#define ALS_MV_AT_1000LX    2400.0f
#define LUX_FULL_SCALE      1000.0f

// Порог наличия питания на USB (мВ)
#define VUSB_PRESENT_MV     4000

// --- ОЦЕНКА ЗАРЯДА БАТАРЕИ (1S LiPo) ---
// На клеммах видно не ЭДС, а ЭДС минус падение на внутреннем сопротивлении.
// Отсюда и скачки: под нагрузкой показания уезжали вниз, при подключении
// зарядника — вверх. Восстанавливаем ЭДС и уже её кладём на кривую разряда.
//
// Просадка при полной загрузке по току (global_abl_rms = 1.0), мВ. Это лишь
// стартовое значение: прошивка уточняет его сама, сравнивая напряжение на
// холостом ходу с напряжением под нагрузкой (см. updateBatterySoc).
#define BATT_SAG_MV_AT_FULL   500
// Просадка от собственного потребления при включённых DCDC (диоды погашены), мВ
#define BATT_BASE_SAG_MV       30
// Подъём напряжения от тока заряда в фазе CC, мВ. Тоже лишь стартовое значение:
// измеряется в момент подключения зарядника тем же приёмом, что и просадка.
#define BATT_CHG_RISE_MV      100
// Ширина окна спада подъёма к концу заряда, мВ. В фазе CV ток падает почти до
// нуля, вместе с ним исчезает и подъём — иначе к концу заряда шкала занижает.
#define BATT_CHG_TAPER_MV     100

// --- СОСТОЯНИЕ ПИТАНИЯ (двухступенчатое) ---
// PWR_OFF    — оба DCDC выключены
// PWR_SPINUP — включён DCDC №1: работают луч 1, Холл 1 и датчик света,
//              считаются обороты, светодиоды погашены
// PWR_FULL   — включены оба DCDC: работают все 6 лучей и все 6 Холлов, идёт отрисовка
enum PowerState : uint8_t { PWR_OFF = 0, PWR_SPINUP = 1, PWR_FULL = 2 };
extern volatile PowerState power_state;

// --- ГЛОБАЛЬНЫЕ ПЕРЕМЕННЫЕ (Объявления для всех файлов) ---
