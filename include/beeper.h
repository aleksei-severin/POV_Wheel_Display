//  переключением матрицы: в паузе оба вывода возвращены обычному GPIO и
//  держат LOW. Остановить сам канал нельзя — у LEDC в покое один уровень,
//  и инвертированный вывод держал бы на пьезо постоянные 3.3 В.
// =====================================================================

