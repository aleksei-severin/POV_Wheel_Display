#pragma once
#include <Arduino.h>

// =====================================================================
//  Процедурные эффекты
//
//  Кадр не читается из файла, а СЧИТАЕТСЯ на устройстве: скорость меняется
//  в реальном времени, часы идут, радуга живёт во времени — заранее записанным
//  файлом такое не выразить.
//
//  Генератор пишет в свою пару буферов RGB565 (формат кадра тот же, что у
//  старых файлов, поэтому рендер работает без изменений) и публикует готовый
//  кадр подменой frameBuffer. Два буфера, а не один: рендер держит указатель
//  на время сборки сектора, и запись «на месте» показала бы полукадр — на
//  тексте скорости это читалось бы как рваная цифра.
// =====================================================================

// Номера — часть протокола (OP_EFFECT, телеметрия, маска слайдшоу, NVS, веб),
// поэтому удалённые эффекты оставляют свой номер пустым, а не сдвигают
// остальные: иначе сохранённый на колесе эффект и отбор слайдшоу молча
// превратились бы в соседние.
enum EffectId : uint8_t {
    EFF_NONE = 0,
    EFF_SPEED,      // цифры скорости, цвет от зелёного к красному
    EFF_RSVD_2,     // бывший «Огонь» — удалён, номер не переиспользуется
    EFF_RAINBOW,    // вращающийся спектр: скорость и резкость полос настраиваются
    // Диагностический крест из двух максимально тонких линий через центр
    // вращения. Первые 5 с всего цикла — синим целиком, следующие 5 с —
    // каждый из 6 лучей своим цветом (см. fillSectorIntoBuffer() в main.cpp:
    // контент считается там же, а не в этом файле, потому что «какой физически
    // луч сейчас рисует» известно только циклу по ray, генератор эффектов
    // этого не знает — он наполняет общий на все лучи мировой буфер).
    EFF_TESTING,
    EFF_RSVD_5,     // бывшие «Волны» — удалены, номер не переиспользуется
    EFF_CLOCK,      // цифровые часы hh.mm.ss и дата yyyy.mm.dd, цвет настраивается
    EFF_TEXT,       // строка вдоль обода; маску рисует телефон (см. OP_TEXT_* в povble.h)
    EFF_COUNT
};

// Существующий эффект: не «выключено», не за пределами и не пустой номер.
static inline bool effectValid(int id) {
    return id > EFF_NONE && id < EFF_COUNT && id != EFF_RSVD_2 && id != EFF_RSVD_5;
}

// Маска эффектов в слайдшоу: бит N-1 — эффект N, кроме пустых номеров: старый
// отбор с битами удалённых эффектов этой маской и чистится.
#define EFF_SLIDE_MASK ((uint8_t)(((1u << (EFF_COUNT - 1)) - 1) & \
                                  ~(1u << (EFF_RSVD_2 - 1)) & ~(1u << (EFF_RSVD_5 - 1))))

// Текущий эффект. EFF_NONE — эффекты выключены, кадр берётся из файла.
extern volatile uint8_t effect_id;

// Заявка на смену эффекта из HTTP-обработчика, −1 = нет заявки.
// Запуск и остановка ждут, пока рендер отпустит буфер, — до секунды в худшем
// случае. Делать это прямо в обработчике значит держать задачу AsyncTCP, а с
// ней и весь HTTP; поэтому заявку исполняет fileLoaderTask, как и загрузку файла.
extern volatile int8_t pending_effect;
// Заявку подал человек (OP_EFFECT, /effect) — после запуска эффекта поднять
// request_play_flag, то есть питание первого луча и таймер активности. Ставится
// ДО pending_effect. Автоматические смены (слайдшоу, тик синхронной группы) его
// не ставят: иначе каждое переключение на эффект считалось бы нажатием Play, и
// неподвижное колесо в слайдшоу с эффектами не засыпало бы никогда.
extern volatile bool pending_effect_play;

// Скорость, на которой шрифт становится полностью красным (км/ч). Живёт в
// SettingsBlob, а не в /fx.cfg: так было задолго до остальных параметров.
extern volatile uint16_t effect_speed_red;

// ---- Параметры эффектов, настраиваемые из приложения (OP_FX_GET / OP_FX_SET) ----
// Цвет часов устроен так же, как цвет «Текста»: один цвет или радуга, которая
// течёт по углу. Радуга-эффект — скорость вращения и резкость переходов: от
// плавного спектра до семи чистых полос «красный…фиолетовый».
struct FxParams {
    uint16_t speed_red;     // км/ч, 5…200
    uint8_t  rb_speed;      // радуга: 0…100, 100 — два оборота спектра в секунду
    uint8_t  rb_sharp;      // радуга: 0 — плавный спектр, 100 — чистые полосы
    uint8_t  clk_mode;      // часы: 0 — один цвет, 1 — радуга
    uint8_t  clk_r, clk_g, clk_b;
    uint8_t  clk_speed;     // часы, радуга: 0…100, как у «Текста»
};
void effectsFxGet(FxParams& p);
// Значения зажимаются; во флеш — отложенно, через effectsFxFlush().
void effectsFxSet(const FxParams& p);
// Записывает изменённые параметры в /fx.cfg. Только когда отрисовка
// остановлена — как и effectsTextFlush().
void effectsFxFlush();

// Строит таблицы и создаёт задачу-генератор. Вызывать один раз из setup().
void effectsInit();

// Включает эффект. Гасит ленту на время подмены буфера — как и загрузчик
// файла, иначе рендер прочитает освобождённую память. false — не хватило PSRAM
// или такого эффекта нет (см. effectValid()).
bool effectsStart(uint8_t id);

// Останавливает генератор и отдаёт PSRAM обратно.
// ОБЯЗАН вызываться загрузчиком файла до подмены frameBuffer: иначе генератор
// продолжит писать в память, которую тот уже освободил.
void effectsStop();

// Короткое имя для лога и веб-интерфейса.
const char* effectName(uint8_t id);

// Текущая скорость колеса, км/ч. Считается из оборотов и длины окружности.
float currentSpeedKmh();

// ---- Эффект «Текст» ----
// Строку по окружности рисует телефон (его шрифты, кириллица, сглаживание) и
// присылает маску яркости 360 × 44; колесо только красит её — одним цветом или
// радугой, которая течёт по углу. Маска и цвет живут в /text.fx и переживают сон.

// Сжатый (raw deflate) блоб [u8 len][строка UTF-8][маска 360 × 44] — распаковать
// и применить. false — не распаковался или не того размера.
bool effectsTextSetBlob(const uint8_t* comp, size_t len);
// Цвет: mode 0 — r/g/b, 1 — радуга со скоростью speed (0…100).
void effectsTextSetStyle(uint8_t mode, uint8_t r, uint8_t g, uint8_t b, uint8_t speed);
void effectsTextGetStyle(uint8_t& mode, uint8_t& r, uint8_t& g, uint8_t& b, uint8_t& speed);
// Копирует сжатый блоб в dst (не больше cap), возвращает его длину (0 — не задан).
size_t effectsTextBlob(uint8_t* dst, size_t cap);
// Записывает изменённые текст и цвет в /text.fx. Вызывать только когда отрисовка
// остановлена — запись флеша морозит renderingTask (см. flushSettings()).
void effectsTextFlush();
