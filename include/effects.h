#pragma once
#include <Arduino.h>

// =====================================================================
//  Процедурные эффекты
//
//  Кадр не читается из файла, а СЧИТАЕТСЯ на устройстве: скорость меняется
//  в реальном времени, огонь и плазма живут во времени — заранее записанным
//  файлом такое не выразить.
//
//  Генератор пишет в свою пару буферов RGB565 (формат кадра тот же, что у
//  старых файлов, поэтому рендер работает без изменений) и публикует готовый
//  кадр подменой frameBuffer. Два буфера, а не один: рендер держит указатель
//  на время сборки сектора, и запись «на месте» показала бы полукадр — на
//  тексте скорости это читалось бы как рваная цифра.
// =====================================================================

enum EffectId : uint8_t {
    EFF_NONE = 0,
    EFF_SPEED,      // цифры скорости, цвет от зелёного к красному
    EFF_FIRE,       // огонь от ступицы к ободу
    EFF_RAINBOW,    // вращающийся спектр
    EFF_PLASMA,     // плазма
    EFF_RIPPLE,     // концентрические волны
    EFF_CLOCK,      // часы со стрелками
    EFF_COUNT
};

// Текущий эффект. EFF_NONE — эффекты выключены, кадр берётся из файла.
extern volatile uint8_t effect_id;

// Заявка на смену эффекта из HTTP-обработчика, −1 = нет заявки.
// Запуск и остановка ждут, пока рендер отпустит буфер, — до секунды в худшем
// случае. Делать это прямо в обработчике значит держать задачу AsyncTCP, а с
// ней и весь HTTP; поэтому заявку исполняет fileLoaderTask, как и загрузку файла.
extern volatile int8_t pending_effect;

// Скорость, на которой шрифт становится полностью красным (км/ч).
extern volatile uint16_t effect_speed_red;

// Строит таблицы и создаёт задачу-генератор. Вызывать один раз из setup().
void effectsInit();

// Включает эффект. Гасит ленту на время подмены буфера — как и загрузчик
// файла, иначе рендер прочитает освобождённую память. false — не хватило PSRAM.
bool effectsStart(uint8_t id);

// Останавливает генератор и отдаёт PSRAM обратно.
// ОБЯЗАН вызываться загрузчиком файла до подмены frameBuffer: иначе генератор
// продолжит писать в память, которую тот уже освободил.
void effectsStop();

// Короткое имя для лога и веб-интерфейса.
const char* effectName(uint8_t id);

// Текущая скорость колеса, км/ч. Считается из оборотов и длины окружности.
float currentSpeedKmh();
